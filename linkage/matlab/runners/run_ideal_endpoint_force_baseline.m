function write_configuration_text(path, configuration)
output_file = fopen(path, 'w');
assert(output_file >= 0, 'Could not create configuration text snapshot.');
cleanup = onCleanup(@() fclose(output_file));
config = configuration.base;

fprintf(output_file, 'MATLAB: %s\n', version);
fprintf(output_file, 'dt: %.17g s\n', config.dt);
fprintf(output_file, 't_final: %.17g s\n', config.t_final);
fprintf(output_file, 'accel_Kp: %s\n', mat2str(config.accel_Kp));
fprintf(output_file, 'accel_Kd: %s\n', mat2str(config.accel_Kd));
fprintf(output_file, 'W_tau: %s\n', mat2str(config.W_tau));
fprintf(output_file, 'lambda_u: %.17g\n', config.lambda_u);
fprintf(output_file, 'lambda_du: %.17g\n', config.lambda_du);
fprintf(output_file, 'u_min [Ft Fn] N: %s\n', mat2str(config.u_min'));
fprintf(output_file, 'u_max [Ft Fn] N: %s\n', mat2str(config.u_max'));
fprintf(output_file, 'du_max [Ft Fn] N/s: %s\n', ...
    mat2str(config.du_max'));
fprintf(output_file, 'oracle_Kp: %s\n', mat2str(config.oracle_Kp));
fprintf(output_file, 'oracle_Kd: %s\n', mat2str(config.oracle_Kd));
fprintf(output_file, 'trajectories: %s\n', ...
    strjoin(configuration.trajectories, ', '));
fprintf(output_file, 'profiles: %s\n', ...
    strjoin(configuration.profiles, ', '));
fprintf(output_file, '%s\n', configuration.force_interpretation);
fprintf(output_file, '%s\n', configuration.authority_note);
fprintf(output_file, '%s\n', configuration.scope_note);
fprintf(output_file, '%s\n', configuration.initialization_note);
for index = 1:numel(configuration.profiles)
    p = configuration.profile_parameters{index};
    fprintf(output_file, ...
        ['profile=%s length_scale=%.4f mass_scale=%.4f ' ...
        'L1=%.6f L2=%.6f m1=%.6f m2=%.6f sc=%.6f\n'], ...
        p.profile_name, p.length_scale, p.mass_scale, ...
        p.L1, p.L2, p.m1, p.m2, p.sc);
end
end
