function create_representative_gif(result, gif_path, output_dir)
figure_handle = figure('Visible', 'off', ...
    'Color', 'w', 'Position', [20, 20, 1400, 820]);
layout = tiledlayout(figure_handle, 5, 2, ...
    'TileSpacing', 'compact', 'Padding', 'compact');

body_axis = nexttile(layout, 1, [5, 1]);
hold(body_axis, 'on');
axis(body_axis, 'equal');
grid(body_axis, 'on');
p = result.parameters;
reach = p.L1 + p.L2;
xlim(body_axis, [-0.25, reach+0.40]);
ylim(body_axis, [-0.35, reach+0.35]);
xlabel(body_axis, 'X (m)');
ylabel(body_axis, 'Y (m)');
title(body_axis, 'Ideal single-point endpoint force');
body_line = plot(body_axis, nan, nan, 'o-', ...
    'LineWidth', 5, 'MarkerSize', 8, ...
    'Color', [0.10, 0.35, 0.75]);
contact_marker = plot(body_axis, nan, nan, 'o', ...
    'MarkerSize', 10, 'MarkerFaceColor', [0.85, 0.25, 0.15], ...
    'MarkerEdgeColor', 'k');
force_arrow = quiver(body_axis, 0, 0, 0, 0, 0, ...
    'LineWidth', 2.5, 'Color', [0.85, 0.15, 0.10], ...
    'MaxHeadSize', 0.8);
text(body_axis, 0.02, 0.98, ...
    'Force arrow scale: 1 N = 0.0012 m', ...
    'Units', 'normalized', 'VerticalAlignment', 'top');

t = result.t;
q_axis = nexttile(layout, 2);
hold(q_axis, 'on');
plot(q_axis, t, rad2deg(result.q_ref(1, :)), '--', ...
    'Color', [0.2, 0.4, 0.9]);
plot(q_axis, t, rad2deg(result.q_ref(2, :)), '--', ...
    'Color', [0.9, 0.4, 0.2]);
q1_actual = plot(q_axis, nan, nan, '-', ...
    'Color', [0.05, 0.2, 0.65], 'LineWidth', 1.5);
q2_actual = plot(q_axis, nan, nan, '-', ...
    'Color', [0.70, 0.15, 0.05], 'LineWidth', 1.5);
grid(q_axis, 'on');
xlim(q_axis, [t(1), t(end)]);
ylabel(q_axis, 'Angle (deg)');
title(q_axis, 'q_1/q_2 reference and actual');
legend(q_axis, {'q_1 ref', 'q_2 ref', 'q_1', 'q_2'}, ...
    'Location', 'eastoutside');

force_axis = nexttile(layout, 4);
hold(force_axis, 'on');
Ft_line = plot(force_axis, nan, nan, 'LineWidth', 1.3);
Fn_line = plot(force_axis, nan, nan, 'LineWidth', 1.3);
force_norm_line = plot(force_axis, nan, nan, 'k-', 'LineWidth', 1.3);
grid(force_axis, 'on');
xlim(force_axis, [t(1), t(end)]);
ylabel(force_axis, 'Force (N)');
title(force_axis, 'Local cuff force');
legend(force_axis, {'F_t', 'F_n', '||F||'}, ...
    'Location', 'eastoutside');

motion_axis = nexttile(layout, 6);
hold(motion_axis, 'on');
acceleration_line = plot(motion_axis, nan, nan, ...
    'Color', [0.1, 0.55, 0.2], 'LineWidth', 1.3);
jerk_line = plot(motion_axis, nan, nan, ...
    'Color', [0.55, 0.15, 0.65], 'LineWidth', 1.3);
grid(motion_axis, 'on');
xlim(motion_axis, [t(1), t(end)]);
ylabel(motion_axis, 'Norm');
title(motion_axis, 'Acceleration (deg/s^2) and jerk (deg/s^3)');
legend(motion_axis, {'||ddq||', '||jerk||'}, ...
    'Location', 'eastoutside');

error_axis = nexttile(layout, 8);
hold(error_axis, 'on');
tracking_line = plot(error_axis, nan, nan, ...
    'Color', [0.10, 0.35, 0.75], 'LineWidth', 1.3);
path_line = plot(error_axis, nan, nan, ...
    'Color', [0.85, 0.25, 0.15], 'LineWidth', 1.3);
grid(error_axis, 'on');
xlim(error_axis, [t(1), t(end)]);
ylabel(error_axis, 'Error (deg)');
title(error_axis, 'Tracking and coordinated-path error');
legend(error_axis, {'||q-q_{ref}||', '|path deviation|'}, ...
    'Location', 'eastoutside');

condition_axis = nexttile(layout, 10);
yyaxis(condition_axis, 'left');
condition_line = plot(condition_axis, nan, nan, ...
    'Color', [0.20, 0.20, 0.20], 'LineWidth', 1.3);
ylabel(condition_axis, 'cond(A)');
yyaxis(condition_axis, 'right');
saturation_line = stairs(condition_axis, nan, nan, ...
    'Color', [0.85, 0.20, 0.15], 'LineWidth', 1.3);
ylim(condition_axis, [-0.05, 1.05]);
ylabel(condition_axis, 'Saturation');
grid(condition_axis, 'on');
xlim(condition_axis, [t(1), t(end)]);
xlabel(condition_axis, 'Time (s)');
title(condition_axis, 'Contact-map conditioning and hard saturation');

axes_with_markers = [q_axis, force_axis, motion_axis, ...
    error_axis, condition_axis];
time_markers = gobjects(size(axes_with_markers));
for marker_index = 1:numel(axes_with_markers)
    marker_axis = axes_with_markers(marker_index);
    hold(marker_axis, 'on');
    time_markers(marker_index) = plot(marker_axis, ...
        [t(1), t(1)], ylim(marker_axis), 'k:', 'LineWidth', 0.8, ...
        'HandleVisibility', 'off');
end

frame_indices = unique(round(linspace(1, numel(t), 65)));
frame_path = fullfile(output_dir, 'representative_frame.png');
force_scale = 0.0012;
delay_time = result.config.t_final / numel(frame_indices);

for frame_number = 1:numel(frame_indices)
    index = frame_indices(frame_number);
    geometry = kinematics(result.state(1:2, index), p);
    contact = shank_contact_kinematics( ...
        result.state(1:2, index), result.state(3:4, index), p);
    points = [geometry.hip, geometry.knee, geometry.ankle];
    set(body_line, 'XData', points(1, :), 'YData', points(2, :));
    set(contact_marker, 'XData', contact.position(1), ...
        'YData', contact.position(2));
    world_force = result.force_world(:, index);
    set(force_arrow, 'XData', contact.position(1), ...
        'YData', contact.position(2), ...
        'UData', force_scale*world_force(1), ...
        'VData', force_scale*world_force(2));
    title(body_axis, sprintf( ...
        'Coordinated path, nominal: t = %.2f s, ||F|| = %.1f N', ...
        t(index), norm(result.force_local(:, index))));

    active = 1:index;
    set(q1_actual, 'XData', t(active), ...
        'YData', rad2deg(result.state(1, active)));
    set(q2_actual, 'XData', t(active), ...
        'YData', rad2deg(result.state(2, active)));
    set(Ft_line, 'XData', t(active), ...
        'YData', result.force_local(1, active));
    set(Fn_line, 'XData', t(active), ...
        'YData', result.force_local(2, active));
    set(force_norm_line, 'XData', t(active), ...
        'YData', vecnorm(result.force_local(:, active), 2, 1));
    set(acceleration_line, 'XData', t(active), ...
        'YData', rad2deg(vecnorm( ...
        result.acceleration(:, active), 2, 1)));
    set(jerk_line, 'XData', t(active), ...
        'YData', rad2deg(vecnorm(result.jerk(:, active), 2, 1)));
    set(tracking_line, 'XData', t(active), ...
        'YData', rad2deg(result.tracking_error_norm(active)));
    set(path_line, 'XData', t(active), ...
        'YData', rad2deg(abs(result.path_error(active))));
    set(condition_line, 'XData', t(active), ...
        'YData', result.condition_number(active));
    set(saturation_line, 'XData', t(active), ...
        'YData', double(result.hard_saturation(active)));
    for marker_index = 1:numel(time_markers)
        set(time_markers(marker_index), ...
            'XData', [t(index), t(index)]);
    end

    exportgraphics(figure_handle, frame_path, 'Resolution', 90);
    rgb_frame = imread(frame_path);
    [indexed_frame, color_map] = rgb2ind(rgb_frame, 256);
    if frame_number == 1
        imwrite(indexed_frame, color_map, gif_path, 'gif', ...
            'LoopCount', Inf, 'DelayTime', delay_time);
    else
        imwrite(indexed_frame, color_map, gif_path, 'gif', ...
            'WriteMode', 'append', 'DelayTime', delay_time);
    end
end

close(figure_handle);
if isfile(frame_path)
    delete(frame_path);
end
end


