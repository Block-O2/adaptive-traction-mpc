function run_ideal_endpoint_force_baseline()
%RUN_IDEAL_ENDPOINT_FORCE_BASELINE Headless deterministic endpoint-force matrix.

set(groot, 'DefaultFigureVisible', 'off');
runner_dir = fileparts(mfilename('fullpath'));
repo_root = fileparts(fileparts(fileparts(runner_dir)));
output_dir = fullfile(repo_root, 'linkage', 'results', 'local', ...
    'ideal_endpoint_force_baseline');
runs_dir = fullfile(output_dir, 'runs');
if ~isfolder(output_dir)
    mkdir(output_dir);
end
if ~isfolder(runs_dir)
    mkdir(runs_dir);
end

diary_path = fullfile(output_dir, 'baseline_console.log');
if isfile(diary_path)
    delete(diary_path);
end
diary(diary_path);
diary_cleanup = onCleanup(@() diary('off'));

trajectories = [ ...
    "knee_dominant", ...
    "coordinated_path", ...
    "conflicting_boundary"];
profiles = ["nominal", "short_light", "tall_heavy"];
actuator_modes = ["endpoint_force", "oracle_joint_torque"];
base_config = ideal_endpoint_force_config();

profile_parameters = cell(1, numel(profiles));
for profile_index = 1:numel(profiles)
    profile_parameters{profile_index} = default_parameters( ...
        profiles(profile_index));
end
validate_references(trajectories, base_config, profile_parameters{1});
write_command_record(fullfile(output_dir, 'commands.txt'));

version_file = fopen(fullfile(output_dir, 'matlab_version.txt'), 'w');
assert(version_file >= 0, 'Could not create MATLAB version record.');
fprintf(version_file, '%s\n', version);
fclose(version_file);

configuration = struct();
configuration.trajectories = trajectories;
configuration.profiles = profiles;
configuration.actuator_modes = actuator_modes;
configuration.base = base_config;
configuration.profile_parameters = profile_parameters;
configuration.force_interpretation = [ ...
    "u=[Ft;Fn] in the rotating shank-contact frame; " ...
    "F_world=[t n]u; tau_contact=Jc'F_world."];
configuration.authority_note = [ ...
    "Endpoint-force cases have no joint torque. Oracle cases use the " ...
    "retained true-model computed-torque PD and therefore have different " ...
    "actuator authority."];
configuration.scope_note = [ ...
    "Ideal bidirectional cuff upper bound only; no robot dynamics, SDK, " ...
    "patient active torque, hidden clipping, or clinical-safety claim."];
configuration.initialization_note = [ ...
    "q and dq start exactly on the reference. The previous cuff command " ...
    "starts at the same hard-bounded steady reference solution, so the " ...
    "first commanded force rate is zero."];
save(fullfile(output_dir, 'configuration_snapshot.mat'), 'configuration');
write_configuration_text(fullfile(output_dir, ...
    'configuration_snapshot.txt'), configuration);

record_count = numel(trajectories) * numel(profiles) * ...
    numel(actuator_modes);
records = repmat(empty_record(), record_count, 1);
record_index = 0;
representative = [];

fprintf('IDEAL ENDPOINT FORCE BASELINE MATLAB: %s\n', version);
fprintf('IDEAL ENDPOINT FORCE OUTPUT: %s\n', output_dir);
fprintf('IDEAL ENDPOINT FORCE RUN COUNT: %d\n', record_count);

for trajectory_index = 1:numel(trajectories)
    for profile_index = 1:numel(profiles)
        p = profile_parameters{profile_index};
        for mode_index = 1:numel(actuator_modes)
            record_index = record_index + 1;
            config = base_config;
            config.trajectory_name = trajectories(trajectory_index);
            actuator_mode = actuator_modes(mode_index);
            run_id = sprintf('%s__%s__%s', ...
                char(config.trajectory_name), char(p.profile_name), ...
                char(actuator_mode));

            result = simulate_ideal_endpoint_force_episode( ...
                config, p, actuator_mode);
            save(fullfile(runs_dir, run_id + ".mat"), ...
                'result', '-v7');

            records(record_index) = make_record( ...
                run_id, config, p, actuator_mode, result.metrics);
            writetable(struct2table(records(record_index)), ...
                fullfile(runs_dir, run_id + "_metrics.csv"));

            if config.trajectory_name == "coordinated_path" && ...
                    p.profile_name == "nominal" && ...
                    actuator_mode == "endpoint_force"
                representative = result;
            end

            fprintf(['  %02d/%02d %-68s completed=%d ' ...
                'rmse=[%.3f, %.3f]deg residual=%.3fNm ' ...
                'sat=%.3f cond95=%.2f limits=[%d,%d]\n'], ...
                record_index, record_count, run_id, ...
                result.metrics.completed, ...
                rad2deg(result.metrics.rmse_rad(1)), ...
                rad2deg(result.metrics.rmse_rad(2)), ...
                result.metrics.torque_residual_rms_Nm, ...
                result.metrics.hard_saturation_fraction, ...
                result.metrics.condition_p95, ...
                result.metrics.joint_limit_violation_count, ...
                result.metrics.velocity_limit_violation_count);
        end
    end
end

aggregate = struct2table(records);
writetable(aggregate, fullfile(output_dir, 'aggregate_metrics.csv'));
save(fullfile(output_dir, 'aggregate_metrics.mat'), ...
    'aggregate', 'configuration');

if isempty(representative)
    error('IdealEndpointForce:MissingRepresentativeRun', ...
        'The nominal coordinated endpoint-force run was not captured.');
end
gif_path = fullfile(output_dir, ...
    'representative_coordinated_path_nominal.gif');
create_representative_gif(representative, gif_path, output_dir);

visible_figures = findall(groot, 'Type', 'figure', 'Visible', 'on');
if ~isempty(visible_figures)
    error('IdealEndpointForce:VisibleFigure', ...
        'The headless runner created a visible figure.');
end
gif_files = dir(fullfile(output_dir, '*.gif'));
if numel(gif_files) ~= 1
    error('IdealEndpointForce:GifCount', ...
        'Expected exactly one representative GIF, found %d.', ...
        numel(gif_files));
end

endpoint_rows = aggregate.actuator_mode == "endpoint_force";
oracle_rows = aggregate.actuator_mode == "oracle_joint_torque";
fprintf(['IDEAL ENDPOINT FORCE SUMMARY: endpoint_completed=%d/%d ' ...
    'oracle_completed=%d/%d signal_nonfinite=%d ' ...
    'joint_limit_samples=%d velocity_limit_samples=%d gif=%s\n'], ...
    sum(aggregate.completed(endpoint_rows)), sum(endpoint_rows), ...
    sum(aggregate.completed(oracle_rows)), sum(oracle_rows), ...
    sum(aggregate.signal_nonfinite_count), ...
    sum(aggregate.joint_limit_violation_count), ...
    sum(aggregate.velocity_limit_violation_count), gif_path);
end


function validate_references(trajectories, config, p)
t = 0:config.dt:config.t_final;
for trajectory = trajectories
    q = zeros(2, numel(t));
    dq = zeros(2, numel(t));
    ddq = zeros(2, numel(t));
    for index = 1:numel(t)
        [q(:, index), dq(:, index), ddq(:, index)] = ...
            rehabilitation_reference_trajectory(t(index), trajectory);
    end
    if any(q < p.q_min | q > p.q_max, 'all')
        error('IdealEndpointForce:ReferenceJointLimit', ...
            'Reference %s exceeds a configured joint range.', trajectory);
    end
    if any(abs(dq) > p.dq_max, 'all')
        error('IdealEndpointForce:ReferenceVelocityLimit', ...
            'Reference %s exceeds a configured velocity range.', trajectory);
    end
    if any(abs(ddq) > p.reference_ddq_max, 'all')
        error('IdealEndpointForce:ReferenceAccelerationLimit', ...
            'Reference %s exceeds a configured acceleration range.', ...
            trajectory);
    end
end
end


