function print_initial_admissibility(name,a)
fprintf(['INITIAL ADMISSIBILITY %s pass=%d q=[%.9g %.9g]deg ' ...
    'soft_clearance=[%.9g %.9g]deg soft_tau=[%.9g %.9g]Nm ' ...
    'bed=%.9g/%.9gN true_eq=[%.9g %.9g]N model_eq=[%.9g %.9g]N ' ...
    'ungoverned_candidate=[%.9g %.9g]N ' ...
    'true_candidate_alpha=[%.9g %.9g]deg/s^2 ' ...
    'model_alpha=[%.9g %.9g]deg/s^2\n'],name,a.pass,a.q_deg, ...
    a.true_soft_clearance_deg,a.true_soft_torque_Nm,a.bed_force_N, ...
    a.bed_force_threshold_N,a.true_equilibrium_force_N, ...
    a.model_equilibrium_force_N,a.first_command_force_N, ...
    a.true_first_command_alpha_deg_s2,a.model_first_command_alpha_deg_s2);
end


function write_initial_admissibility(path,name,a)
file=fopen(path,'w');assert(file>=0);cleanup=onCleanup(@()fclose(file));
fprintf(file,'case=%s\npass=%d\n',name,a.pass);
fprintf(file,'q_deg=[%.12g %.12g]\ndq_deg_s=[%.12g %.12g]\n', ...
    a.q_deg,a.dq_deg_s);
fprintf(file,['true_soft_lower_start_deg=[%.12g %.12g]\n' ...
    'true_soft_upper_start_deg=[%.12g %.12g]\n' ...
    'true_soft_clearance_deg=[%.12g %.12g]\n' ...
    'model_soft_clearance_deg=[%.12g %.12g]\n'], ...
    a.true_soft_lower_start_deg,a.true_soft_upper_start_deg, ...
    a.true_soft_clearance_deg,a.model_soft_clearance_deg);
fprintf(file,['true_soft_torque_Nm=[%.12g %.12g]\n' ...
    'model_soft_torque_Nm=[%.12g %.12g]\n' ...
    'soft_torque_tolerance_Nm=%.12g\n'],a.true_soft_torque_Nm, ...
    a.model_soft_torque_Nm,a.soft_torque_tolerance_Nm);
fprintf(file,['rom_lower_margin_deg=[%.12g %.12g]\n' ...
    'rom_upper_margin_deg=[%.12g %.12g]\n'], ...
    a.true_rom_lower_margin_deg,a.true_rom_upper_margin_deg);
fprintf(file,'bed_force_N=%.12g\nbed_force_threshold_N=%.12g\n', ...
    a.bed_force_N,a.bed_force_threshold_N);
fprintf(file,['true_equilibrium_force_N=[%.12g %.12g]\n' ...
    'model_equilibrium_force_N=[%.12g %.12g]\n' ...
    'ungoverned_nominal_first_candidate_force_N=[%.12g %.12g]\n' ...
    'force_bound_N=%.12g\n'], ...
    a.true_equilibrium_force_N,a.model_equilibrium_force_N, ...
    a.first_command_force_N,a.force_bound_N);
fprintf(file,['true_equilibrium_alpha_deg_s2=[%.12g %.12g]\n' ...
    'true_ungoverned_candidate_alpha_deg_s2=[%.12g %.12g]\n' ...
    'model_ungoverned_candidate_alpha_deg_s2=[%.12g %.12g]\n' ...
    'legacy_true_first_alpha_deg_s2=[%.12g %.12g]\n'], ...
    a.true_equilibrium_alpha_deg_s2,a.true_first_command_alpha_deg_s2, ...
    a.model_first_command_alpha_deg_s2,a.legacy_true_first_alpha_deg_s2);
end


