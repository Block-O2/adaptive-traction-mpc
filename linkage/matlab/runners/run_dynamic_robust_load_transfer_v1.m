function write_summary(path,records)
file=fopen(path,'w');assert(file>=0);cleanup=onCleanup(@()fclose(file));
fprintf(file,'Dynamic robust load transfer V1\nMATLAB %s\n',version);
for k=1:numel(records)
    r=records(k);fprintf(file,['%s: %s, phase %s, tracking %d, ' ...
        'takeover %.9g s, duration %.9g s, final s %.9g, ' ...
        'peak robot %.9g N, peak bed %.9g N, min robust %.9g N, ' ...
        'min dynamic %.9g N\n'],r.case_name,r.classification, ...
        r.failure_phase,r.tracking_entered,r.takeover_duration_s, ...
        r.duration_s,r.final_s,r.peak_force_norm_N,r.peak_bed_force_N, ...
        r.min_robust_static_margin_N,r.min_dynamic_margin_N);
end
end


function create_cross_case_figure(records,output_dir)
T=struct2table(records);fig=figure('Visible','off','Color','w');
bar(categorical(T.case_name),[T.peak_force_norm_N,T.peak_bed_force_N, ...
    T.min_robust_static_margin_N,T.min_dynamic_margin_N]);grid on;
ylabel('N');legend('peak robot norm','peak bed','min robust','min dynamic');
exportgraphics(fig,fullfile(output_dir,'cross_case_summary.png'),'Resolution',180);close(fig);
end
