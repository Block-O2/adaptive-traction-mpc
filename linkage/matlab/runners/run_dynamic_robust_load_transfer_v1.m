function run_dynamic_robust_load_transfer_v1()
%RUN_DYNAMIC_ROBUST_LOAD_TRANSFER_V1 Formal fixed capability experiment.
%
% Stage 2 is executed only when the nominal Stage 1 reaches TASK_COMPLETE.

set(groot,'DefaultFigureVisible','off');
runner_dir=fileparts(mfilename('fullpath'));
repo_root=fileparts(fileparts(fileparts(runner_dir)));
root=fullfile(repo_root,'linkage','results','local', ...
    'dynamic_robust_load_transfer_v1');
run_id=char(datetime('now','TimeZone','UTC','Format','yyyyMMdd_HHmmss'));
output_dir=fullfile(root,run_id);mkdir(output_dir);
diary(fullfile(output_dir,'console.log'));cleanup=onCleanup(@()diary('off'));
fprintf('DYNAMIC ROBUST LOAD TRANSFER V1 MATLAB: %s\n',version);
fprintf('OUTPUT DIRECTORY: %s\n',output_dir);
fprintf(['FORMAL COMMAND: matlab -batch "addpath(genpath(''' ...
    'linkage/matlab'')); run_dynamic_robust_load_transfer_v1"\n']);

nominal=human_two_link_v2_parameters(1.72,75);
config=dynamic_robust_v1_config();
calibration=bed_supported_v1_calibrate_hip_height(nominal,config);
plan=hybrid_tube_v1_build_plan(nominal,config);
uncertainty=bed_supported_v1_registered_uncertainty_set(nominal);
case_names=["nominal","mild","moderate","adverse"];
results=cell(1,4);records=repmat(empty_record(),0,1);
admissibility_records=repmat(empty_admissibility_record(),0,1);

[results{1},initialization]=run_case( ...
    case_names(1),nominal,config,plan,calibration,output_dir);
records(end+1)=make_record(case_names(1),results{1}); %#ok<AGROW>
admissibility_records(end+1)=make_admissibility_record( ...
    case_names(1),initialization); %#ok<AGROW>
if results{1}.terminal_state=="TASK_COMPLETE"
    for k=1:3
        item=uncertainty.combined_cases(k);
        plant=bed_supported_v1_parameter_override(nominal,item.override);
        [results{k+1},initialization]=run_case( ...
            case_names(k+1),plant,config,plan,calibration,output_dir);
        records(end+1)=make_record(case_names(k+1),results{k+1}); %#ok<AGROW>
        admissibility_records(end+1)=make_admissibility_record( ...
            case_names(k+1),initialization); %#ok<AGROW>
    end
else
    fprintf('STAGE 2 SKIPPED: nominal classification=%s\n', ...
        results{1}.terminal_state);
end
save(fullfile(output_dir,'formal_results.mat'),'results','records', ...
    'admissibility_records','nominal','config','calibration', ...
    'uncertainty','-v7.3');
writetable(struct2table(records),fullfile(output_dir,'case_metrics.csv'));
writetable(struct2table(admissibility_records), ...
    fullfile(output_dir,'initial_admissibility.csv'));
write_summary(fullfile(output_dir,'summary.txt'),records);
if numel(records)>1,create_cross_case_figure(records,output_dir);end
if ~isempty(findall(groot,'Type','figure','Visible','on'))
    error('DynamicRobustV1:VisibleFigure','Formal runner created a visible figure.');
end
end


function [result,initialization]=run_case( ...
        name,plant,config,plan,calibration,output_dir)
nominal=human_two_link_v2_parameters(1.72,75);
case_config=config;case_config.case_name="dynamic_robust_"+name;
fprintf('RUN CASE %s\n',name);
initialization=dynamic_robust_v1_initial_admissibility( ...
    nominal,plant,calibration,case_config);
case_dir=fullfile(output_dir,char(name));mkdir(case_dir);
write_initial_admissibility( ...
    fullfile(case_dir,'initial_admissibility.txt'),name,initialization);
print_initial_admissibility(name,initialization);
if ~initialization.pass
    error('DynamicRobustV1:InitialAdmissibilityFailed', ...
        'Case %s failed initial admissibility; rollout was not started.',name);
end
result=simulate_dynamic_robust_load_transfer_v1( ...
    case_config,nominal,plant,plan,calibration,initialization);
save(fullfile(case_dir,'result.mat'),'result','-v7.3');
dynamic_robust_v1_create_artifacts(result,case_dir);
fprintf('CASE %s classification=%s t=%.3f s=%.6f peak=%.3fN\n', ...
    name,result.terminal_state,result.t(end),result.task_s(end), ...
    result.metrics.peak_force_norm_N);
end


